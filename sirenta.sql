-- =========================================================
-- 1. ENUM TYPES
-- ENUM digunakan untuk membatasi pilihan nilai dalam kolom.
-- Jadi, kolom hanya bisa menerima nilai yang sudah ditentukan.
-- =========================================================

-- Menentukan jenis pengguna.
CREATE TYPE user_role AS ENUM ('applicant', 'admin');

-- Menentukan pilihan tema tampilan.
CREATE TYPE user_theme AS ENUM ('light', 'dark');

-- Menentukan status pendaftaran.
CREATE TYPE application_status AS ENUM (
    'draft',
    'submitted',
    'passed',
    'failed'
);

-- Menentukan jenjang pendidikan.
CREATE TYPE degree_level AS ENUM (
    'SD', 'SMP', 'SMA/SMK', 'D3', 'S1', 'S2', 'S3'
);


-- =========================================================
-- 2. FUNCTION UPDATED_AT
-- PostgreSQL tidak memiliki ON UPDATE CURRENT_TIMESTAMP
-- seperti MySQL.
-- Oleh karena itu, kita membuat FUNCTION dan TRIGGER.
-- =========================================================

-- Function ini akan mengubah updated_at menjadi waktu
-- terbaru setiap kali data mengalami UPDATE.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;


-- =========================================================
-- 3. AUTHENTICATION
-- Bagian ini mengatur data pengguna dan proses login.
-- =========================================================


-- ---------------------------------------------------------
-- TABEL USERS
-- Menyimpan informasi seluruh pengguna aplikasi.
-- ---------------------------------------------------------

CREATE TABLE users (
    -- ID otomatis sebagai Primary Key.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- NIM harus unik dan tidak boleh kosong.
    nim VARCHAR(20) NOT NULL UNIQUE,

    -- Informasi identitas pengguna.
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,

    -- Menyimpan password yang sudah di-hash.
    password_hash VARCHAR(255) NOT NULL,

    -- Menentukan role pengguna (applicant/admin).
    role user_role NOT NULL DEFAULT 'applicant',

    -- Foto profil pengguna.
    photo_path VARCHAR(255),

    -- Tema tampilan default adalah dark.
    theme user_theme NOT NULL DEFAULT 'dark',

    -- Menentukan apakah akun masih aktif.
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    -- Mencatat waktu terakhir pengguna login.
    last_login_at TIMESTAMP,

    -- Mencatat waktu pembuatan dan perubahan data.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- TRIGGER USERS
-- Menjalankan function set_updated_at() setiap kali
-- data pengguna diperbarui.
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


-- ---------------------------------------------------------
-- TABEL LOGIN_LOGS
-- Menyimpan riwayat aktivitas login pengguna.
-- ---------------------------------------------------------

CREATE TABLE login_logs (
    -- ID otomatis sebagai Primary Key.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- NIM pengguna yang mencoba login.
    nim VARCHAR(20) NOT NULL,

    -- Foreign Key menuju tabel users.
    -- Boleh NULL jika pengguna tidak ditemukan.
    user_id BIGINT,

    -- TRUE = login berhasil, FALSE = login gagal.
    success BOOLEAN NOT NULL,

    -- Informasi perangkat dan alamat IP.
    ip_address VARCHAR(45),
    user_agent VARCHAR(255),

    -- Waktu terjadinya percobaan login.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Jika akun dihapus, user_id menjadi NULL.
    CONSTRAINT fk_login_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE SET NULL
);

-- INDEX mempercepat pencarian berdasarkan NIM dan waktu.
CREATE INDEX idx_login_nim
ON login_logs (nim, created_at);


-- ---------------------------------------------------------
-- TABEL AUTH_SESSIONS
-- Menyimpan token sesi login pengguna.
-- ---------------------------------------------------------

CREATE TABLE auth_sessions (
    -- Token session sebagai Primary Key.
    id CHAR(64) PRIMARY KEY,

    -- Menghubungkan session dengan pengguna.
    user_id BIGINT NOT NULL,

    -- Menentukan waktu kedaluwarsa session.
    expires_at TIMESTAMP NOT NULL,

    -- Waktu pembuatan session.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Jika pengguna dihapus, session ikut dihapus.
    CONSTRAINT fk_sess_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);

-- Mempercepat pencarian session berdasarkan user_id.
CREATE INDEX idx_sess_user
ON auth_sessions (user_id);


-- ---------------------------------------------------------
-- TABEL PASSWORD_RESETS
-- Menyimpan data untuk proses lupa password.
-- ---------------------------------------------------------

CREATE TABLE password_resets (
    -- ID otomatis sebagai Primary Key.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Menghubungkan permintaan reset dengan pengguna.
    user_id BIGINT NOT NULL,

    -- Menyimpan token reset yang sudah di-hash.
    token_hash CHAR(64) NOT NULL,

    -- Batas waktu penggunaan token.
    expires_at TIMESTAMP NOT NULL,

    -- Waktu token digunakan, NULL jika belum digunakan.
    used_at TIMESTAMP,

    -- Waktu permintaan reset dibuat.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Jika pengguna dihapus, data reset ikut dihapus.
    CONSTRAINT fk_reset_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE
);


-- =========================================================
-- 4. PHASES
-- Menyimpan jadwal setiap tahap recruitment.
-- Contoh: Phase 1 - Registration.
-- =========================================================

CREATE TABLE phases (
    -- ID otomatis sebagai Primary Key.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Urutan tahap recruitment (1, 2, 3, dan seterusnya).
    -- Harus unik dan berada dalam rentang 0-255.
    seq SMALLINT NOT NULL UNIQUE
        CHECK (seq BETWEEN 0 AND 255),

    -- Nama dan deskripsi tahap.
    name VARCHAR(100) NOT NULL,
    description TEXT,

    -- Jadwal mulai dan berakhirnya tahap.
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,

    -- Menentukan apakah tahap sedang aktif.
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    -- Waktu selesai harus lebih besar dari waktu mulai.
    CHECK (end_at > start_at)
);


-- =========================================================
-- 5. APPLICATIONS
-- Menyimpan data pendaftaran pengguna pada setiap phase.
-- Satu pengguna hanya boleh memiliki satu aplikasi
-- untuk satu phase yang sama.
-- =========================================================

CREATE TABLE applications (
    -- ID otomatis sebagai Primary Key.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Menghubungkan aplikasi dengan pemilik akun.
    user_id BIGINT NOT NULL,

    -- Menghubungkan aplikasi dengan tahap recruitment.
    phase_id BIGINT NOT NULL,

    -- Status awal pendaftaran adalah draft.
    status application_status NOT NULL DEFAULT 'draft',

    -- Waktu pengguna mengirimkan pendaftaran.
    submitted_at TIMESTAMP,

    -- Waktu data aplikasi dibuat dan diperbarui.
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Mencegah satu pengguna membuat dua aplikasi
    -- pada phase yang sama.
    CONSTRAINT uq_user_phase
        UNIQUE (user_id, phase_id),

    -- Relasi ke tabel users.
    -- Jika pengguna dihapus, aplikasinya ikut dihapus.
    CONSTRAINT fk_app_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- Relasi ke tabel phases.
    -- Aplikasi harus memiliki phase yang valid.
    CONSTRAINT fk_app_phase
        FOREIGN KEY (phase_id)
        REFERENCES phases(id)
);


-- TRIGGER APPLICATIONS
-- Memperbarui updated_at secara otomatis
-- ketika data aplikasi mengalami UPDATE.
CREATE TRIGGER trg_applications_updated_at
BEFORE UPDATE ON applications
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


